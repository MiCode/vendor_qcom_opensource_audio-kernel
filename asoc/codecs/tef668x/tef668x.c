static int tef668x_i2c_probe(struct i2c_client *client,
			     const struct i2c_device_id *id)
{
	int ret = -1;
	struct tef668x_data *tef668x;

	dev_info(&client->dev, "%s: tef668x i2c probe E, addr = %x\n", __func__,
		 client->addr);

	/* Allocate driver data */
	tef668x = devm_kzalloc(&client->dev, sizeof(struct tef668x_data),
			       GFP_KERNEL);
	if (!tef668x)
		return -ENOMEM;

	/* Initialize client driver structure */
	tef668x->client = client;
	tef668x->dev = &client->dev;

	/* regmap config */
	i2c_set_clientdata(client, tef668x);

	ret = tef668x_start_init(tef668x);
	if (ret < 0)
		return ret;

	tef668x->regmap = devm_regmap_init_i2c(client, &tef668x_regmap);
	dev_info(tef668x->dev, "allocate register map done\n");
	if (IS_ERR(tef668x->regmap)) {
		ret = PTR_ERR(tef668x->regmap);
		dev_err(tef668x->dev, "Failed to allocate register map: %d\n",
			ret);
		return ret;
	}

	/* create attr */
	ret = sysfs_create_group(&client->dev.kobj, &tef668x_attribute_group);
	if (ret < 0) {
		dev_err(tef668x->dev, "error creating sysfs attr files");
	}

	/* 1. accroding to i2c devive parse dtsi
	   2. gpio control in tef668x driver use mixer kcontrol implement */
	tef668x_priv = tef668x;

	dev_info(&client->dev, "%s: tef668x i2c probe done, ret %d\n", __func__,
		 ret);

	return ret;
}

static void tef668x_i2c_remove(struct i2c_client *client)
{
	dev_info(&client->dev, "%s: tef668x i2c remove\n", __func__);
	/*rm attr node*/
	sysfs_remove_group(&client->dev.kobj, &tef668x_attribute_group);
	return;
}

