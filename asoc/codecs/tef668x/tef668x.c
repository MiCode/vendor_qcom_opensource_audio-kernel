/*-----------------------------------------------------------------------
Function name:	Radio_SetFreq
Input:		mode:
                              TEF663X_PRESETMODE.,TEF663X_SEARCHMODE
                              TEF663X_AFUPDATEMODE,TEF663X_JUMPMODE...
                        Freq:
Output:	
Description:
------------------------------------------------------------------------*/
static int Radio_SetFreq(struct tef668x_data *tef668x, U8 mode, U8 Band,
			 U16 Freq)
{
	int ret = -1;
	AR_TuningAction_t A2Mode = eAR_TuningAction_Preset;

	if (!tef668x) {
		return -EPERM;
	}
	/*frequency baundary check*/
	if ((Freq > FreqBaundConfig[Radio_CurrentBand].MaxFreq) ||
	    (Freq < FreqBaundConfig[Radio_CurrentBand].MinFreq)) {
		Freq = FreqBaundConfig[Radio_CurrentBand].MinFreq;
	}
	if (Band >= MaxBandNum) {
		dev_err(tef668x->dev, "invalid band: 0x%x\n", Band);
		return -EINVAL;
	}

	Radio_CurrentBand = Band;
	switch (Band) {
	case FM1_BAND:
	case FM2_BAND:
	case FM3_BAND:
		Band = 0;
		break;
	case LW_BAND:
		Band = 1;
		break;
	case MW_BAND:
		Band = 2;
		break;
	case SW_BAND:
		Band = 3;
		break;
	}

	Radio_CurrentFreq = Freq;
	StationRecord[Radio_CurrentBand].Freq[0] = Radio_CurrentFreq;

	if (Is_Radio_Atomic2) {
		switch (mode) {
		case Radio_PRESETMODE:
			A2Mode = eAR_TuningAction_Preset;
			break;
		case Radio_SEARCHMODE:
			A2Mode = eAR_TuningAction_Search;
			break;
		case Radio_AFUPDATEMODE:
			A2Mode = eAR_TuningAction_AF_Update;
			break;
		case Radio_JUMPMODE:
			A2Mode = eAR_TuningAction_Jump;
			break;
		case Radio_CHECKMODE:
			A2Mode = eAR_TuningAction_Check;
			break;
		}
		ret = Radio_Tune_To(tef668x, A2Mode, Freq);
		if (ret < 0) {
			dev_err(tef668x->dev, "Radio_SetFreq fail, freq = %d\n",
				Freq);
			return ret;
		}
	} else if (Is_Radio_Hero) {
		/*update pll*/
		//RadioDrv_UpdatePll(mode,Band,Freq); //xiaomi delete and add log
		dev_err(tef668x->dev,
			"Radio is Hero dev type, please check the radio chip\n");
		return -EINVAL;
	}
	return 0;
}

