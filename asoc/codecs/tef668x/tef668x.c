static void Radio_ChangeFreqOneStep(U8 UpDown)
{
	int step;

	step = Radio_GetFreqStep(Radio_CurrentBand);
	if (UpDown == 1) { /*increase one step*/
		Radio_CurrentFreq += step;
		/*frequency baundary check	*/
		if (Radio_CurrentFreq >
		    FreqBaundConfig[Radio_CurrentBand].MaxFreq) {
			Radio_CurrentFreq =
				FreqBaundConfig[Radio_CurrentBand].MinFreq;
		}
	} else { /*decrease one step*/
		Radio_CurrentFreq -= step;
		/*frequency baundary check*/
		if (Radio_CurrentFreq <
		    FreqBaundConfig[Radio_CurrentBand].MinFreq) {
			Radio_CurrentFreq =
				FreqBaundConfig[Radio_CurrentBand].MaxFreq;
		}
	}
}

