static int devTEF668x_Set_Cmd(struct tef668x_data *tef668x,
			      TEF668x_MODULE module, U8 cmd, int len, ...)
{
	int ret = -1;
	int i = 0;
	U8 buf[TEF668x_CMD_LEN_MAX] = { 0 };
	U16 temp = 0;
	va_list vArgs;
	va_start(vArgs, len);

	buf[0] = module; //module,		FM/AM/APP
	buf[1] = cmd; //cmd,		1,2,10,...
	buf[2] = 1; //index, 		always 1

	//fill buffer with 16bits one by one
	for (i = 3; i < len; i++) {
		temp = va_arg(vArgs, int); //the size only int valid for compile

		buf[i++] = High_16bto8b(temp);
		buf[i] = Low_16bto8b(temp);
	}
	va_end(vArgs);

	dev_info(tef668x->dev,
		 "devTEF668x_Set_Cmd addr = %x reg_addr: 0x%x, reg_data :0x%x,"
		 "0x%x,0x%x,0x%x,0x%x,0x%x,0x%x,0x%x",
		 tef668x->client->addr, buf[0], buf[1], buf[2], buf[3], buf[4],
		 buf[5], buf[6], buf[7], buf[8]);

	ret = i2c_master_send(tef668x->client, buf, len);
	if (ret < 0)
		dev_err(tef668x->dev, "i2c master send error");

	return ret;
}

