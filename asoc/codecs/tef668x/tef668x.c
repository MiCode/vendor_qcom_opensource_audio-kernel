/*====================================================
 Function:Tuner_Auto_Seek
 notes: xiaomi Change from Tuner_Seek_Sub in Tuner_Proc.c
=========================================================*/
static int Tuner_Auto_Seek(struct tef668x_data *tef668x, bool direction)
{
	int ret = -1;

	if (!tef668x) {
		return -EPERM;
	}
	Radio_ScanStartFreq = Radio_GetCurrentFreq(); //save current freq
	/*increase or decreas one step*/
	if (direction) {
		F_Tune_UP = 1;
	} else {
		F_Tune_UP = 0;
	}
	/*to process seek event step by step*/
	do {
		Radio_ChangeFreqOneStep(F_Tune_UP);
		/*write "new programmble value" into PLL*/
		ret = Tuner_Update_ProgCnt(tef668x, Radio_SEARCHMODE);
		if (ret < 0) {
			dev_err(tef668x->dev, "auto seek execute fail\n");
			goto end;
		}
		Radio_ClearCurrentStation(); //clear station number
		/*station check*/
		if (PRESENT_STATION ==
		    Radio_CheckStation(tef668x)) { /*get good station*/
			dev_info(tef668x->dev,
				 "auto seek get good station, freq = %d\n",
				 Radio_GetCurrentFreq());
			break;
		} else { /*no station*/
			continue; // loop seek
		}
	} while (Radio_ScanStartFreq != Radio_GetCurrentFreq());

	ret = Tuner_Update_ProgCnt(tef668x, Radio_PRESETMODE);
	if (ret < 0) {
		dev_err(tef668x->dev, "auto seek freq set fail, freq = %d\n",
			Radio_GetCurrentFreq());
	}
end:
	Tuner_Event_End();
	return ret;
}

