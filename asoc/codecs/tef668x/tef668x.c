/*
[ w 40 80 01 [ r 0001 ]
Alternatively Wait 50 ms.
Set reference frequency
*/
static int DevTEF668x_Idle_state(struct tef668x_data *tef668x)
{
	int ret = -1;

	dev_info(tef668x->dev,
		 "DevTEF668x_Idle_state enter DevTEF668x_State= %d\n",
		 DevTEF668x_State);

	if (DevTEF668x_State != eDevTEF668x_Boot_state) {
		//Set reference frequency
		if (SUCCESS == APPL_Set_ReferenceClock(tef668x, TEF668x_REF_CLK,
						       TEF668x_IS_EXT_CLK)) {
			//Activate : APPL_Activate mode = 1.[ w 40 05 01 0001 ]
			ret = APPL_Activate(tef668x);
			if (ret > 0) {
				usleep_range(TEF668x_TIMER_WAIT_IDLE,
					     TEF668x_TIMER_WAIT_IDLE +
						     100); //50 ms
			}
		}
	}
	return ret;
}

static int tef668x_patch_load(struct tef668x_data *tef668x,
			      const unsigned char *pLutBytes, size_t size)
{
	unsigned char buf[TEF668x_SPLIT_SIZE + 1] = { 0 };
	size_t len = 0, sum = 0;
	int ret = -1;
	buf[0] = 0x1b;

	while (size) {
		len = (size > TEF668x_SPLIT_SIZE) ? TEF668x_SPLIT_SIZE : size;
		size -= len;

		memcpy(buf + 1, pLutBytes, len);
		pLutBytes += len;
		sum += len; //try

		ret = i2c_master_send(tef668x->client, buf, len + 1);
		usleep_range(1000, 1000 + 100); //1 ms
		if (ret < 0) {
			dev_err(tef668x->dev, "tef668x_patch_load error\n");
			break;
		}
		if (len == 24)
			dev_info(
				tef668x->dev,
				"tef668x_patch_load addr = %x reg_addr: 0x%x, reg_data :%x,"
				"%x,%x,%x,%x,%x,%x,%x,%x,%x,%x,"
				"%x,%x,%x,%x,%x,%x,%x,%x,%x,%x,%x,%x,%x\n,",
				tef668x->client->addr, buf[0], buf[1], buf[2],
				buf[3], buf[4], buf[5], buf[6], buf[7], buf[8],
				buf[9], buf[10], buf[11], buf[12], buf[13],
				buf[14], buf[15], buf[16], buf[17], buf[18],
				buf[19], buf[20], buf[21], buf[22], buf[23],
				buf[24]);
		else
			dev_info(
				tef668x->dev,
				"tef668x_patch_load addr = %x reg_addr: 0x%x, reg_data :%x,"
				"%x,%x,%x,%x,%x,%x,%x,%x,%x,%x,%x,"
				"%x,%x,%x,%x,%x,%x,%x,%x,%x,%x\n,",
				tef668x->client->addr, buf[0], buf[1], buf[2],
				buf[3], buf[4], buf[5], buf[6], buf[7], buf[8],
				buf[9], buf[10], buf[11], buf[12], buf[13],
				buf[14], buf[15], buf[16], buf[17], buf[18],
				buf[19], buf[20], buf[21], buf[22]);
		//delay for debug output
		if ((sum % 128) == 0) {
			//usleep_range(TEF668x_TIMER_WAIT_IDLE, TEF668x_TIMER_WAIT_IDLE + 100);//50 ms
		}
	}

	return ret;
}

static int tef668x_patch_init(struct tef668x_data *tef668x)
{
	int ret = -1;
	int i = 0;

	dev_info(tef668x->dev, "tef668x_patch_init enter\n");
	//[ w 1C 0000 ]
	ret = tef668x_i2c_writes(tef668x, devTEF668x_Patch_CmdTab1);
	if (ret < 0) {
		dev_err(tef668x->dev, "int tab1 error\n");
		return ret;
	}
	//[ w 1C 0074 ]
	ret = tef668x_i2c_writes(tef668x, devTEF668x_Patch_CmdTab2);
	if (ret < 0) {
		dev_err(tef668x->dev, "int tab2 error\n");
		return ret;
	}
	//pPatchBytes use PATCH.c
	dev_info(tef668x->dev, "tef668x_patch_load pPatchBytes\n");
	ret = tef668x_patch_load(tef668x, pPatchBytes, PatchSize);
	if (ret < 0) {
		while (i < TEF_I2C_RETRIES) {
			dev_err(tef668x->dev,
				"int pPatchBytes error,wait 10ms,retry five\n");
			usleep_range(TEF668x_TIMER_POWER,
				     TEF668x_TIMER_POWER +
					     100); //every + 10 ms.
			ret = tef668x_patch_load(tef668x, pPatchBytes,
						 PatchSize);
			if (ret < 0) {
				dev_err(tef668x->dev,
					"int pPatchBytes error\n");
				i++;
				if (i == 5)
					return ret;
			} else
				break;
		}
	}
	//[ w 1C 0000 ]
	ret = tef668x_i2c_writes(tef668x, devTEF668x_Patch_CmdTab1);
	if (ret < 0) {
		dev_err(tef668x->dev, "int tab1 error\n");
		return ret;
	}
	//[ w 1C 0075 ]
	ret = tef668x_i2c_writes(tef668x, devTEF668x_Patch_CmdTab3);
	if (ret < 0) {
		dev_err(tef668x->dev, "int tab3 error\n");
		return ret;
	}
	//pPatchBytes use PATCH.c
	dev_info(tef668x->dev, "tef668x_patch_load  pLutBytes \n");
	ret = tef668x_patch_load(tef668x, pLutBytes, LutSize);
	if (ret < 0) {
		dev_err(tef668x->dev,
			"int pLutBytes error,wati 10ms,retry again\n");
		usleep_range(TEF668x_TIMER_POWER,
			     TEF668x_TIMER_POWER + 100); //every + 10 ms.
		ret = tef668x_patch_load(tef668x, pLutBytes, LutSize);
		if (ret < 0) {
			dev_err(tef668x->dev, "int pLutBytes two error\n");
			return ret;
		}
	}
	//[ w 1C 0000 ]
	ret = tef668x_i2c_writes(tef668x, devTEF668x_Patch_CmdTab1);
	if (ret < 0) {
		dev_err(tef668x->dev, "int tab1 error\n");
		return ret;
	}
	//[ w 14 0001 ]
	ret = tef668x_i2c_writes(tef668x, devTEF668x_Patch_CmdTab4);
	if (ret < 0) {
		dev_err(tef668x->dev, "int tab error\n");
		return ret;
	}
	dev_info(tef668x->dev, "tef668x_patch_init leave\n");
	return ret;
}

static int tef668x_boot_state(struct tef668x_data *tef668x)
{
	int ret = 0;
	dev_info(tef668x->dev, "tef668x_boot_state enter\n");
	ret = tef668x_patch_init(tef668x);

	usleep_range(TEF668x_TIMER_WAIT_IDLE,
		     TEF668x_TIMER_WAIT_IDLE + 100); //every + 50 ms.

	dev_info(tef668x->dev, "tef668x_boot_state leave\n");
	return 1;
}

static int tef668x_start_init(struct tef668x_data *tef668x)
{
	int ret = -1;

	dev_info(tef668x->dev, "tef668x_start_init enter\n");

	ret = tef668x_i2c_writes(tef668x, devTEF668x_Patch_CmdTab0);
	if (ret < 0) {
		dev_err(tef668x->dev, "int tab0 error\n");
		return ret;
	}
	usleep_range(TEF668x_TIMER_POWER,
		     TEF668x_TIMER_POWER + 100); //every + 10 ms.

	ret = tef668x_i2c_writes(tef668x, devTEF668x_Patch_CmdTab5);
	if (ret < 0) {
		dev_err(tef668x->dev, "int tab5 error\n");
		return ret;
	}
	usleep_range(TEF668x_TIMER_POWER,
		     TEF668x_TIMER_POWER + 100); //every + 10 ms.
	ret = tef668x_boot_state(tef668x);
	if (ret > 0) {
		DevTEF668x_State = eDevTEF668x_Idle_state;
	} else {
		dev_err(tef668x->dev, "boot state error\n");
		return ret;
	}
	usleep_range(TEF668x_TIMER_WAIT_IDLE,
		     TEF668x_TIMER_WAIT_IDLE + 100); //50 ms

	//APPL_Get_Operation_Status [ w 40 80 01 [ r 0001 ]
	ret = DevTEF668x_Idle_state(tef668x);
	if (ret > 0) {
		DevTEF668x_State = eDevTEF668x_Wait_Active;

	} else {
		dev_err(tef668x->dev, "DevTEF668x_Idle_state error\n");
		return ret;
	}

	usleep_range(TEF668x_TIMER_WAIT_IDLE,
		     TEF668x_TIMER_WAIT_IDLE + 100); //50 ms
	ret = DevTEF668x_Wait_Active(tef668x);
	if (ret > 0) {
		DevTEF668x_State = eDevTEF668x_Active_state;
	} else {
		dev_err(tef668x->dev, "DevTEF668x_Wait_Active error\n");
		return ret;
	}

	DevTEF668x_Active_state(tef668x);

	ret = tef668x_i2c_writes(tef668x, devTEF668x_Patch_CmdTab6);
	if (ret < 0) {
		dev_err(tef668x->dev, "int tab6 error\n");
		return ret;
	}

	ret = tef668x_i2c_writes(tef668x, devTEF668x_Patch_CmdTab7);
	if (ret < 0) {
		dev_err(tef668x->dev, "int tab7 error\n");
		return ret;
	}
	ret = tef668x_i2c_writes(tef668x, devTEF668x_Patch_CmdTab8);
	if (ret < 0) {
		dev_err(tef668x->dev, "int tab8 error\n");
		return ret;
	}

	return 0;
}

