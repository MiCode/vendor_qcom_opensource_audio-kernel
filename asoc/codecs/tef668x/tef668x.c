static int tef668x_i2c_writes(struct tef668x_data *tef668x,
			      const unsigned char *tab)
{
	int ret = -1;
	int len = 0;
	unsigned char buf[20] = { 0 };

	len = tab[0];
	memcpy(buf, &tab[1], len);

	if (len == 3) {
		dev_info(
			tef668x->dev,
			"tef668x_i2c_writes addr = %x reg_addr: 0x%x, reg_data :%x %x",
			tef668x->client->addr, tab[1], tab[2], tab[3]);
	} else if (len == 5) {
		dev_info(tef668x->dev,
			 "tef668x_i2c_writes addr = %x reg_addr: 0x%x,"
			 "reg_data :%x %x %x %x",
			 tef668x->client->addr, tab[1], tab[2], tab[3], tab[4],
			 tab[5]);
	} else if (len == 7) {
		dev_info(tef668x->dev,
			 "tef668x_i2c_writes addr = %x reg_addr: 0x%x, "
			 "reg_data :%x %x %x %x %x %x",
			 tef668x->client->addr, tab[1], tab[2], tab[3], tab[4],
			 tab[5], tab[6], tab[7]);
	} else if (len == 9) {
		dev_info(tef668x->dev,
			 "tef668x_i2c_writes addr = %x reg_addr: 0x%x, "
			 "reg_data :%x %x %x %x %x %x %x %x",
			 tef668x->client->addr, tab[1], tab[2], tab[3], tab[4],
			 tab[5], tab[6], tab[7], tab[8], tab[9]);
	} else if (len == 11) {
		dev_info(tef668x->dev,
			 "tef668x_i2c_writes addr = %x reg_addr: 0x%x, "
			 "reg_data :%x %x %x %x %x %x %x %x %x %x",
			 tef668x->client->addr, tab[1], tab[2], tab[3], tab[4],
			 tab[5], tab[6], tab[7], tab[8], tab[9], tab[10],
			 tab[11]);
	} else if (len == 13) {
		dev_info(tef668x->dev,
			 "tef668x_i2c_writes addr = %x reg_addr: 0x%x, "
			 "reg_data :%x %x %x %x %x %x %x %x %x %x %x %x",
			 tef668x->client->addr, tab[1], tab[2], tab[3], tab[4],
			 tab[5], tab[6], tab[7], tab[8], tab[9], tab[10],
			 tab[11], tab[12], tab[13]);
	} else {
		dev_info(tef668x->dev,
			 "tef668x_i2c_writes addr = %x, len = %d, "
			 "not normal length, please check\n",
			 tef668x->client->addr, len);
	}

	ret = i2c_master_send(tef668x->client, buf, len);
	if (ret < 0) {
		dev_err(tef668x->dev, "i2c master send error\n");
		return ret;
	}
	return 1;
};

static int tef668x_i2c_reads(struct tef668x_data *tef668x,
			     unsigned char reg_addr, unsigned char *data_buf,
			     unsigned int data_len)
{
	int ret;
	struct i2c_msg msg[] = {
		[0] = {
			.addr = tef668x->client->addr,
			.flags = 0,
			.len = sizeof(uint8_t),
			.buf = &reg_addr,
			},
		[1] = {
			.addr = tef668x->client->addr,
			.flags = I2C_M_RD,
			.len = data_len,
			.buf = data_buf,
			},
	};

	ret = i2c_transfer(tef668x->client->adapter, msg, ARRAY_SIZE(msg));
	if (ret < 0) {
		dev_err(tef668x->dev, "transfer failed.");
		return ret;
	}

	return 0;
}

static int tef668x_i2c_write(struct tef668x_data *tef668x,
			     unsigned char reg_addr, unsigned char reg_data0,
			     unsigned char reg_data1)
{
	int ret = -1;
	unsigned char cnt = 0;
	unsigned char Tab[] = { 3, 0x00, 0x00, 0x00 };

	Tab[1] = reg_addr;
	Tab[2] = reg_data0;
	Tab[3] = reg_data1;

	while (cnt < TEF_I2C_RETRIES) {
		ret = tef668x_i2c_writes(tef668x, Tab);
		if (ret < 0) {
			dev_err(tef668x->dev,
				"tef668x_i2c_write cnt=%d error=%d", cnt, ret);
		} else {
			dev_info(tef668x->dev,
				 "tef668x_i2c_write reg_addr: 0x%x, "
				 "reg_data :0x%x,reg_data :0x%x",
				 (uint8_t)reg_addr, (uint8_t)reg_data0,
				 (uint8_t)reg_data1);
			break;
		}
		cnt++;
	}

	if (ret < 0) {
		dev_err(tef668x->dev,
			"retray 5 times,still error,try usleep 3s, "
			"i2c_write cnt=%d error=%d",
			cnt, ret);
		usleep_range(TEF_RETRY_WAIT_TIME, TEF_RETRY_WAIT_TIME + 100);
		ret = tef668x_i2c_writes(tef668x, Tab);
		if (ret < 0) {
			dev_err(tef668x->dev,
				"usleep 3s still ereror, i2c_write cnt=%d error=%d",
				cnt, ret);
		}
	}

	return ret;
}

static int tef668x_i2c_read(struct tef668x_data *tef668x,
			    unsigned char reg_addr, unsigned int *reg_data)
{
	int ret = -1;
	unsigned char cnt = 0;
	unsigned char buf[1];

	while (cnt < TEF_I2C_RETRIES) {
		ret = tef668x_i2c_reads(tef668x, reg_addr, buf, 1);
		if (ret < 0) {
			dev_err(tef668x->dev, "i2c_read cnt=%d error=%d", cnt,
				ret);
		} else {
			dev_err(tef668x->dev,
				"reg_addr: 0x%02x, reg_data :0x%02x, buf[0] :0x%02x",
				(uint8_t)reg_addr, (uint8_t)(*reg_data),
				buf[0]);
			*reg_data = (buf[0] << 0);
			dev_err(tef668x->dev,
				"reg_addr: 0x%02x, reg_data :0x%02x, buf[0] :0x%02x",
				(uint8_t)reg_addr, (uint8_t)(*reg_data),
				buf[0]);
			break;
		}
		cnt++;
	}
	if (ret < 0) {
		dev_err(tef668x->dev,
			"retray 5 times,still error,try usleep 3s, i2c_write cnt=%d error=%d",
			cnt, ret);
		usleep_range(TEF_RETRY_WAIT_TIME, TEF_RETRY_WAIT_TIME + 100);
		ret = tef668x_i2c_reads(tef668x, reg_addr, buf, 1);
		if (ret < 0) {
			dev_err(tef668x->dev,
				"usleep 3s still ereror, i2c_read cnt=%d error=%d",
				cnt, ret);
		}
	}

	return ret;
}

