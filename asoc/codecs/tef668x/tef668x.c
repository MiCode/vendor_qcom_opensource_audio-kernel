/*--------------------------------------------------------------------
 Function:Radio_CheckStation
 notes: xiaomi Change from Radio_CheckStation in Tuner_Proc.c
 Input: 
      Null
 OutPut:
      Null
 Desp:
     check station if aviable
---------------------------------------------------------------------*/
static int Radio_CheckStation(struct tef668x_data *tef668x)
{
	int checkifstep = NO_STATION;
	unsigned char i = 0, status = 0, threshold = 0;
	unsigned char usn = 0, wam = 0, modulation = 0;
	int16_t level = 0, offset = 0, bandwidth = 0, time = 0;

	bool fm = (Radio_CurrentBand <= FM3_BAND);

	if (!tef668x) {
		return -EPERM;
	}

	threshold = fm ? RADIO_FM_LEVEL_AVAILABLE_TIME :
			 RADIO_AM_LEVEL_AVAILABLE_TIME; // fm at least delay 5ms
	usleep_range(TEF668x_TIMER_WAIT_SEEK,
		     TEF668x_TIMER_WAIT_SEEK + 100); //xiaomi add 10 ms wait
	if (Radio_Get_QRS(tef668x, fm) < threshold) {
		checkifstep = NO_STATION;
		dev_info(tef668x->dev, " Radio_Get_QRS  fail, freq = %d\n",
			 Radio_CurrentFreq);
		goto end;
	}

	for (i = 0; i < 3; i++) { /*Check 3 times*/
		threshold = fm ? ((SeekSenLevel == HIGH) ? FM_SCAN_LEVEL_HI :
							   FM_SCAN_LEVEL) :
				 ((SeekSenLevel == HIGH) ? AM_SCAN_LEVEL_HI :
							   AM_SCAN_LEVEL);
		usleep_range(
			TEF668x_TIMER_WAIT_SEEK,
			TEF668x_TIMER_WAIT_SEEK +
				100); //xiaomi add 10 ms * 3 = 30.  10ms min --30ms max
		level = Radio_Get_Level(tef668x, fm);
		if (threshold > level) { //exit check
			checkifstep = NO_STATION;
			dev_info(
				tef668x->dev,
				"func:%s,line:%d, fm:%d, level:%d , threshold:%d, freq:%d,"
				"Radio_Get_Level  fail\n",
				__func__, __LINE__, fm, level, threshold,
				Radio_CurrentFreq);
			goto end;
		}
	}
	while (time++ <
	       RADIO_USN_AVAILABLE_TIME) { // xiaomi add wait RADIO_USN_AVAILABLE_TIME for max
		dev_info(tef668x->dev, "func:%s,line:%d, freq:%d\n", __func__,
			 __LINE__, Radio_CurrentFreq);
		usleep_range(TEF668x_TIMER_WAIT_USN,
			     TEF668x_TIMER_WAIT_USN +
				     100); //xiaomi add wait 1ms once
		if (Radio_Get_QRS(tef668x, fm) >=
		    RADIO_USN_AVAILABLE_TIME) //wait usn... available (at least 34ms)
		{
			break;
		}
	}
	if (SUCCESS == Radio_Get_Data(tef668x, fm, &status, &level, &usn, &wam,
				      &offset, &bandwidth, &modulation)) {
		checkifstep = NO_STATION;
		if (fm ? ((usn < FM_USN_DISTURBANCE) &&
			  (wam < FM_WAM_DISTURBANCE) &&
			  (offset < FM_FREQ_OFFSET) &&
			  (bandwidth > FM_BAND_WIDTH)) :
			 (offset <
			  AM_FREQ_OFFSET)) //xiaomi add  FM_BAND_WIDTH check for test
		{
			checkifstep = PRESENT_STATION;
			dev_info(
				tef668x->dev,
				"func:%s,line:%d, fm:%d, level:%d, threshold:%d, usn:%d,"
				"wam:%d, offset:%d, bandwidth:%d, freq:%d is good station \n",
				__func__, __LINE__, fm, level, threshold, usn,
				wam, offset, bandwidth, Radio_CurrentFreq);
			goto end;
		}
	}

	checkifstep = NO_STATION;
	dev_info(tef668x->dev,
		 "func:%s,line:%d, fm:%d, level:%d , threshold:%d, usn:%d,"
		 "wam:%d,offset:%d, bandwidth:%d ,freq:%d is bad station \n",
		 __func__, __LINE__, fm, level, threshold, usn, wam, offset,
		 bandwidth, Radio_CurrentFreq);
end:
	return checkifstep;
}

